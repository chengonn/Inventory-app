import { test, expect } from "@playwright/test";
test("stocktake supports mobile cabinet selection, gain/loss/zero and blank rows", async ({ page }, info) => {
  test.skip(process.env.E2E_MOVES_FIXTURE !== "1", "Requires disposable DB fixture runner");
  test.setTimeout(90000);
  await page.goto("/login");
  await page.getByLabel("Email", { exact: true }).fill("owner@example.com");
  await page.getByLabel("密碼", { exact: true }).fill("fixture-password");
  await page.getByRole("button", { name: "登入", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto("/stocktake");
  await page.getByRole("combobox", { name: "櫃位", exact: true }).selectOption({ label: `Count-${info.project.name} / 1` });
  await page.getByRole("button", { name: "載入盤點表", exact: true }).click();
  const field = (type: string) => page.getByLabel(`Count-${info.project.name}-${type} 實際數量`, { exact: true });
  await expect(field("gain")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await field("gain").fill("-1");
  await page.getByRole("button", { name: "預覽盤點", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "非負" })).toBeVisible();
  await field("gain").fill("12.125"); await field("loss").fill("0"); await field("same").fill("10");
  await page.getByRole("button", { name: "預覽盤點", exact: true }).click();
  const preview = page.getByRole("region", { name: "盤點預覽" });
  await expect(preview).toContainText("盤盈 2.125"); await expect(preview).toContainText("盤損 -10.000"); await expect(preview).toContainText("無差額");
  await page.getByRole("button", { name: "返回修改", exact: true }).click();
  await expect(field("gain")).toHaveValue("12.125");
  await page.getByRole("button", { name: "預覽盤點", exact: true }).click();
  await expect(preview).toContainText("目前 10.000");
  await page.getByRole("button", { name: "確認盤點", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("盤點已完成");
  await expect(page.getByText(/無差額，不建立交易/)).toBeVisible();
  await page.getByRole("link", { name: "重新載入，建立下一次盤點" }).click();
  await field("loss").fill("0"); // All other rows blank and unchanged.
  await page.getByRole("button", { name: "預覽盤點", exact: true }).click();
  await expect(preview).toContainText("無差額"); await expect(preview).not.toContainText(`Count-${info.project.name}-gain`);
  await page.getByRole("button", { name: "確認盤點", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("盤點已完成");
  await page.getByRole("link", { name: "查看異動紀錄" }).click();
  await expect(page.getByRole("heading", { name: `盤盈 · Count-${info.project.name}-gain`, exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: `盤損 · Count-${info.project.name}-loss`, exact: true })).toBeVisible();
});
